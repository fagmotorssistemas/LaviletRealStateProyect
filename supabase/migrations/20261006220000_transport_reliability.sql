RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF NEW.kind IN ('inbound','advisor_outbound') THEN
  NEW.payload:=coalesce(NEW.payload,'{}'::jsonb)||jsonb_build_object('transportSequence',NEW.ingest_order);
