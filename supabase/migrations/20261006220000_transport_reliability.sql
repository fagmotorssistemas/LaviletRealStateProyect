-- A response field belongs to a lead; a chat belongs to a contact. Both are
-- shared resources even when their canonical contact keys differ.
CREATE OR REPLACE FUNCTION public.lv_app_resources_overlap(p_left text,p_right text)
RETURNS boolean LANGUAGE sql IMMUTABLE SET search_path='' AS $$
 SELECT coalesce(p_left=p_right OR (
  p_left~'^([1-9][0-9]*|contact):[1-9][0-9]*$' AND p_right~'^([1-9][0-9]*|contact):[1-9][0-9]*$'
  AND (split_part(p_left,':',2)=split_part(p_right,':',2)
   OR (split_part(p_left,':',1)~'^[1-9][0-9]*$' AND split_part(p_left,':',1)=split_part(p_right,':',1)))
 ),false);
$$;

CREATE OR REPLACE FUNCTION public.lv_app_receive(p_events jsonb)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE event jsonb; count_inserted integer:=0; added integer;
BEGIN
 IF p_events IS NULL OR jsonb_typeof(p_events)<>'array' OR jsonb_array_length(p_events)>200 THEN RAISE EXCEPTION 'INVALID_EVENTS'; END IF;
 FOR event IN SELECT value FROM jsonb_array_elements(p_events) LOOP
  IF coalesce(event->>'externalId','')='' OR coalesce(event->>'contactId','')='' THEN RAISE EXCEPTION 'INVALID_EVENT'; END IF;
  INSERT INTO lv_integration_events(tenant_id,project_id,event_key,kind,contact_key,payload,available_at)
  VALUES('a1b2c3d4-0001-4000-8000-000000000001','b1b2c3d4-0001-4000-8000-000000000001',
   'inbound:'||(event->>'externalId'),'inbound',(event->>'kommoId')||':'||(event->>'contactId'),event,now()+interval '30 seconds')
  ON CONFLICT(project_id,event_key) DO NOTHING;
  GET DIAGNOSTICS added=ROW_COUNT; count_inserted:=count_inserted+added;
 END LOOP;
 RETURN count_inserted;
END $$;

CREATE OR REPLACE FUNCTION public.lv_app_receive_advisor_outbound(p_events jsonb)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE event jsonb; count_inserted integer:=0; added integer; resolved_kommo_id bigint; matched_ids bigint[];
BEGIN
 IF p_events IS NULL OR jsonb_typeof(p_events)<>'array' OR jsonb_array_length(p_events)>200 THEN RAISE EXCEPTION 'INVALID_EVENTS'; END IF;
 FOR event IN SELECT value FROM jsonb_array_elements(p_events) LOOP
  IF coalesce(event->>'externalId','')='' OR coalesce(event->>'contactId','')='' OR coalesce(event->>'userId','')='' THEN RAISE EXCEPTION 'INVALID_ADVISOR_EVENT'; END IF;
  resolved_kommo_id:=nullif(event->>'kommoId','')::bigint;
  IF coalesce(resolved_kommo_id,0)<=0 THEN
   SELECT array_agg(DISTINCT l.kommo_id) INTO matched_ids FROM leads l
    WHERE l.tenant_id='a1b2c3d4-0001-4000-8000-000000000001' AND l.project_id='b1b2c3d4-0001-4000-8000-000000000001'
     AND l.contact_id::text=event->>'contactId' AND l.kommo_id>0;
   resolved_kommo_id:=CASE WHEN cardinality(matched_ids)=1 THEN matched_ids[1] END;
   IF cardinality(matched_ids)>1 THEN event:=event||jsonb_build_object('identityAmbiguous',true); END IF;
  END IF;
  IF coalesce(resolved_kommo_id,0)>0 THEN event:=jsonb_set(event,'{kommoId}',to_jsonb(resolved_kommo_id),true); END IF;
  INSERT INTO lv_integration_events(tenant_id,project_id,event_key,kind,contact_key,payload,available_at)
  VALUES('a1b2c3d4-0001-4000-8000-000000000001','b1b2c3d4-0001-4000-8000-000000000001',
   'advisor_outbound:'||(event->>'externalId'),'advisor_outbound',
   coalesce(nullif(resolved_kommo_id,0)::text,'contact')||':'||(event->>'contactId'),event,now()+interval '30 seconds')
  ON CONFLICT(project_id,event_key) DO NOTHING;
  GET DIAGNOSTICS added=ROW_COUNT; count_inserted:=count_inserted+added;
 END LOOP;
 RETURN count_inserted;
END $$;

-- Maintenance does not send Kommo messages and owns a separate lease. The old
-- global send worker still excludes contact workers until Salesbot field-read
-- timing has been verified; this migration does not guess when delivery occurs.
CREATE OR REPLACE FUNCTION public.lv_app_worker_lock(p_token uuid,p_action text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_id uuid;
BEGIN
 IF p_token IS NULL THEN RAISE EXCEPTION 'TOKEN_REQUIRED'; END IF;
 PERFORM pg_advisory_xact_lock(hashtext('lavilet-conversation-workers'));
 IF p_action='acquire' THEN
  IF EXISTS(SELECT 1 FROM lv_integration_events WHERE project_id='b1b2c3d4-0001-4000-8000-000000000001'
    AND kind='lock' AND starts_with(event_key,'__conversation__:') AND lease_until>now()) THEN RETURN false; END IF;
  INSERT INTO lv_integration_events(tenant_id,project_id,event_key,kind,status,claim_token,lease_until)
   VALUES('a1b2c3d4-0001-4000-8000-000000000001','b1b2c3d4-0001-4000-8000-000000000001','__worker__','lock','completed',p_token,now()+interval '3 minutes')
   ON CONFLICT(project_id,event_key) DO UPDATE SET claim_token=p_token,lease_until=now()+interval '3 minutes'
    WHERE lv_integration_events.lease_until IS NULL OR lv_integration_events.lease_until<now() RETURNING id INTO v_id;
 ELSIF p_action IN ('renew','release') THEN
  UPDATE lv_integration_events SET lease_until=CASE WHEN p_action='renew' THEN now()+interval '3 minutes' END,
   claim_token=CASE WHEN p_action='renew' THEN p_token END
   WHERE project_id='b1b2c3d4-0001-4000-8000-000000000001' AND kind='lock'
    AND (event_key IN ('__worker__','__maintenance__') OR starts_with(event_key,'__conversation__:'))
    AND claim_token=p_token AND (p_action='release' OR lease_until>now()) RETURNING id INTO v_id;
 ELSE RAISE EXCEPTION 'INVALID_ACTION'; END IF;
 RETURN v_id IS NOT NULL;
END $$;

